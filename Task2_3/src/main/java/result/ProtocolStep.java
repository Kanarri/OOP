package result;

import model.Candidate;

import java.util.List;
import java.util.Map;

/**
 * Один шаг протокола подсчёта: номер тура, счёт по кандидатам,кто выбыл на этом шаге
 * Единый формат шага для всех методов подсчёта - это нужно, чтобы
 * сравнительная таблица и вывод протокола работали одинаково для
 * плюралити, двух туров, Борда, Кондорсе и STV.
 *
 * Число шагов зависит от метода:
 *  плюралити, Борд, Кондорсе - один шаг
 *   два тура - до двух шагов (первый и второй тур)
 *   STV - столько шагов, сколько раундов исключения потребовалось
 *
 * @param round номер тура/раунда, начиная с {@code 1}
 * @param scores счёт по кандидатам на этом шаге
 * @param eliminated кандидаты, выбывшие на этом шаге
 * @param note короткое пояснение шага
 */
public record ProtocolStep(int round, Map<Candidate, Integer> scores, List<Candidate> eliminated, String note){ }
